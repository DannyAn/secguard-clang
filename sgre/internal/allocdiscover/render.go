package allocdiscover

import (
	"fmt"
	"strings"
)

// Render returns the suggested secguard.toml text. It always emits both the
// [allocators] and [deallocators] tables (possibly empty) so the file is a
// valid, adoptable secguard.toml after the ".suggested" suffix is dropped.
func (r *Result) Render() string {
	var b strings.Builder
	b.WriteString("# Auto-generated by secguard-clang index (sgre build stage).\n")
	b.WriteString("# Review each entry before adopting it into secguard.toml.\n")
	b.WriteString("# To enable: rename this file to secguard.toml (drop the \".suggested\" suffix).\n")
	b.WriteString("# Entries marked \"needs review\" could not be classified with high confidence.\n")
	writeSection(&b, "allocators", r.Allocators)
	writeSection(&b, "deallocators", r.Deallocators)
	return b.String()
}

func writeSection(b *strings.Builder, title string, entries []Entry) {
	fmt.Fprintf(b, "\n[%s]\n", title)
	if len(entries) == 0 {
		b.WriteString("# (none found)\nnames = []\n")
		return
	}
	b.WriteString("names = [\n")
	for _, e := range entries {
		marker := e.Confidence
		if e.Confidence == ConfLow {
			marker = "needs review"
		}
		fmt.Fprintf(b, "    # %s: %s\n", marker, strings.Join(e.Reasons, "; "))
		fmt.Fprintf(b, "    %q,\n", e.Name)
	}
	b.WriteString("]\n")
}
