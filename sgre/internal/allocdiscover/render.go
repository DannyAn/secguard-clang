package allocdiscover

import (
	"fmt"
	"strings"
)

// Render returns the suggested secguard.toml text. It always emits both the
// [allocators] and [deallocators] tables (possibly empty) so the file is a
// valid, adoptable secguard.toml after the ".suggested" suffix is dropped.
//
// Low-confidence ("needs review") candidates are emitted COMMENTED OUT: a
// config-declared deallocator/allocator is trusted by the summary-based
// detectors, so putting an unvetted guess into the live `names` list can turn
// it into an auto-confirmed false positive (e.g. list_init treated as a
// release). They stay visible (and easy to uncomment) but adoption only
// activates high/medium entries.
func (r *Result) Render() string {
	var b strings.Builder
	b.WriteString("# Auto-generated by secguard-clang index (sgre build stage).\n")
	b.WriteString("# Review each entry before adopting it into secguard.toml.\n")
	b.WriteString("# If <project>/.codeagent/secguard.toml exists it takes precedence over this\n")
	b.WriteString("# file (and config files replace rather than merge): merge the entries you\n")
	b.WriteString("# want into that file instead.\n")
	b.WriteString("# Otherwise rename this file to secguard.toml (drop the \".suggested\" suffix).\n")
	b.WriteString("# Only high/medium entries are active below. Entries marked \"needs review\"\n")
	b.WriteString("# are commented out — uncomment one only after checking it really allocates or\n")
	b.WriteString("# releases its first pointer argument.\n")
	writeSection(&b, "allocators", r.Allocators)
	writeSection(&b, "deallocators", r.Deallocators)
	writeSection(&b, "ownership_transfer_calls", r.OwnershipTransfers)
	writeIteratorMacroSection(&b, r.IteratorMacros)
	return b.String()
}

func writeSection(b *strings.Builder, title string, entries []Entry) {
	fmt.Fprintf(b, "\n[%s]\n", title)
	if len(entries) == 0 {
		b.WriteString("# (none found)\nnames = []\n")
		return
	}
	b.WriteString("names = [\n")
	for _, e := range entries {
		if e.Confidence == ConfLow {
			fmt.Fprintf(b, "    # needs review: %s\n", strings.Join(e.Reasons, "; "))
			fmt.Fprintf(b, "    # %q,\n", e.Name)
			continue
		}
		fmt.Fprintf(b, "    # %s: %s\n", e.Confidence, strings.Join(e.Reasons, "; "))
		fmt.Fprintf(b, "    %q,\n", e.Name)
	}
	b.WriteString("]\n")
}

// writeIteratorMacroSection renders the [iterator_macros.macros] section. The
// format is NAME = [index] (the 0-based parameter index the macro writes as
// its iterator variable), NOT names = [...]. The index cannot be inferred from
// the macro body alone, so EVERY entry is emitted commented out with a
// placeholder [0] — the user fills in the correct index after reviewing the
// macro signature. An incorrect index would cause uninit false positives, so
// auto-activating a guess is unsafe.
func writeIteratorMacroSection(b *strings.Builder, entries []Entry) {
	b.WriteString("\n[iterator_macros.macros]\n")
	if len(entries) == 0 {
		b.WriteString("# (none found)\n")
		return
	}
	for _, e := range entries {
		fmt.Fprintf(b, "# %s: %s\n", e.Confidence, strings.Join(e.Reasons, "; "))
		fmt.Fprintf(b, "# %s = [0]  # fill in the iterator parameter index\n", e.Name)
	}
}
