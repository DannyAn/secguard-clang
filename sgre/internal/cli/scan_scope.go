package cli

import (
	"os"
	"path/filepath"
	"strings"

	"github.com/DannyAn/secguard-clang/internal/db"
)

// scanScope reports whether a scan is a COMPLETE-PROGRAM scan (the tree defines
// `main`) or a BOUNDARY scan (a library / a subtree), and — when it is a subtree
// of a larger git worktree — names the enclosing worktree.
//
// The distinction is a product fact, not a heuristic: the null-deref seeding
// policy treats every zero-in-tree-caller pointer parameter of a boundary scan
// as fail-open (its callers are outside the tree). Scanning `repo/src` while
// `main` lives in `repo/app` therefore turns the whole module into an external
// boundary and floods the AI with "is this external caller allowed to pass
// NULL?" candidates that are non-null by the project's own convention. The
// pipeline cannot infer that from a subtree, so the scan must SAY it.
func scanScope(targetPath string, funcs []*db.Function) map[string]interface{} {
	hasEntry := false
	for _, f := range funcs {
		if f.Name == "main" {
			hasEntry = true
			break
		}
	}
	worktree := enclosingWorktree(targetPath)
	scope := map[string]interface{}{
		"has_entry_point":    hasEntry,
		"enclosing_worktree": worktree,
	}
	switch {
	case hasEntry:
		scope["mode"] = "complete-program"
	case worktree != "":
		scope["mode"] = "boundary"
		scope["hint"] = "no entry point (main) in the scanned tree and it is a subtree of the git worktree " +
			worktree + " — every boundary pointer parameter is treated as an external caller's argument (fail-open). " +
			"Scan the worktree root for a complete-program result, or set [scan] boundary_auto_dismiss = \"external\" " +
			"(or \"all\") in secguard.toml to pre-dismiss the fail-open null-deref rows instead of spending AI budget on them."
	default:
		scope["mode"] = "boundary"
		scope["hint"] = "no entry point (main) in the scanned tree — every boundary pointer parameter is treated as an external caller's argument (fail-open). " +
			"Scan the enclosing worktree root, or set [scan] boundary_auto_dismiss = \"external\" (or \"all\") in secguard.toml to pre-dismiss the fail-open null-deref rows."
	}
	return scope
}

// writeBoundaryConfigHint drops a starter secguard.toml next to the scan output
// for a boundary scan. The scan cannot infer the project's entry points or
// non-null framework parameters, so the file is a commented template: the user
// fills in the names instead of copying them out of the report prose.
func writeBoundaryConfigHint(scanDir, target, worktree string) {
	if scanDir == "" {
		return
	}
	var b strings.Builder
	b.WriteString("# Generated by secguard scan for boundary scan ")
	b.WriteString(filepath.Base(scanDir))
	b.WriteString("\n# Target: ")
	b.WriteString(target)
	b.WriteString("\n#\n# Starter file: merge the names you need into your real secguard.toml; do not\n# overwrite an existing one.\n#\n# The scanned tree has no entry point, so every zero-caller pointer parameter\n# is seeded fail-open. Two ways to close the boundary:\n#\n")
	b.WriteString("# 1) Scan the enclosing worktree root (complete-program mode):\n")
	if worktree != "" {
		b.WriteString("#    secguard scan ")
		b.WriteString(worktree)
		b.WriteString("\n")
	} else {
		b.WriteString("#    secguard scan <worktree-root>\n")
	}
	b.WriteString("# 2) Declare the project's real entry points (a firmware task / RTOS thread):\n")
	b.WriteString("[scan]\nentry_points = []\n")
	b.WriteString("# Optionally pre-dismiss fail-open null-deref rows instead of sending them to AI:\n")
	b.WriteString("# boundary_auto_dismiss = \"external\"  # or \"all\"\n\n")
	b.WriteString("# Framework-guaranteed non-null pointer parameters (dispatch user_data, reply_msg, ...):\n")
	b.WriteString("[nullability.non_null_params]\nnames = []\n\n")
	b.WriteString("# Function-like macros whose expansion is a pointer, not a nullable source:\n")
	b.WriteString("[trusted_macros]\nnames = []\n")
	_ = os.WriteFile(filepath.Join(scanDir, "secguard.toml.suggested"), []byte(b.String()), 0644)
}

// enclosingWorktree walks up from targetPath and returns the first ancestor that
// carries a `.git` entry (a directory, or a file for worktrees/submodules). It
// returns "" when the target is not inside a git worktree.
func enclosingWorktree(targetPath string) string {
	dir, err := filepath.Abs(targetPath)
	if err != nil {
		return ""
	}
	if info, err := os.Stat(dir); err == nil && !info.IsDir() {
		dir = filepath.Dir(dir)
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, ".git")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return ""
		}
		dir = parent
	}
}

// scopeMode / scopeWorktree read one field of the scan-scope map without
// threading the whole map through the report data model.
func scopeMode(scope map[string]interface{}) string {
	if v, ok := scope["mode"].(string); ok {
		return v
	}
	return ""
}

func scopeWorktree(scope map[string]interface{}) string {
	if v, ok := scope["enclosing_worktree"].(string); ok {
		return v
	}
	return ""
}
